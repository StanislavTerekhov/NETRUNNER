// Turns models.json into models.iss (included at the end) and models-size.iss (total bytes, included first): Pascal code the one-click installer includes (the list of files it downloads,
// with sizes and SHA-256) and [UninstallDelete] entries so uninstalling removes the downloaded models too.
//   node tools/installer/gen-models-iss.mjs
import fs from 'node:fs'
import path from 'node:path'

const dir = import.meta.dirname
const entries = JSON.parse(fs.readFileSync(path.join(dir, 'models.json'), 'utf8'))
const q = s => `'${String(s).replaceAll("'", "''")}'`
const lines = ['[Code]', '// Generated by gen-models-iss.mjs from models.json — do not edit.', 'procedure AddModels;', 'begin']
let total = 0
for (const e of entries) {
  total += e.size
  const win = e.rel.replaceAll('/', '\\')
  lines.push(`  AddModel(${q(win)}, ${q(e.sha256)}, ${e.size});`)
  const parts = e.source === 'huggingface' ? [{ url: e.url, name: e.rel.replaceAll('/', '__'), sha256: e.sha256, size: e.size }] : e.parts
  for (const p of parts) {
    if (!p.sha256 || !p.size) throw new Error(`${e.rel}: part ${p.name} has no SHA-256/size — run split-release-models.mjs first`)
    lines.push(`  AddPart(${q(p.url)}, ${q(p.name)}, ${q(p.sha256)}, ${p.size});`)
  }
}
lines.push('end;', '', '[UninstallDelete]')
for (const e of entries) lines.push(`Type: files; Name: "{%USERPROFILE}\\NETRUNNER\\models\\${e.rel.replaceAll('/', '\\')}"`)
const dirs = new Set()
for (const e of entries) {
  const parts = e.rel.split('/')
  for (let i = parts.length - 1; i > 0; i--) dirs.add(parts.slice(0, i).join('\\'))
}
for (const d of [...dirs].sort((a, b) => b.split('\\').length - a.split('\\').length)) lines.push(`Type: dirifempty; Name: "{%USERPROFILE}\\NETRUNNER\\models\\${d}"`)
fs.writeFileSync(path.join(dir, 'models.iss'), lines.join('\r\n') + '\r\n')
fs.writeFileSync(path.join(dir, 'models-size.iss'), `; Generated by gen-models-iss.mjs — do not edit.\r\n#define ModelsTotalBytes "${total}"\r\n`)
console.log(`${entries.length} models, ${(total / 1e9).toFixed(1)} GB → models.iss`)
