/**
 * One system prompt and one tool set for every role, so all roles share the head of the prompt (system text + tool
 * definitions, ~5K tokens) and llama-server reuses it from step to step instead of reading it again. The role and its
 * instructions open the task message instead; what a role may not do is enforced by NETRUNNER (rolePolicyReply).
 */
const AGENT_PROMPT =
  'You are a NETRUNNER coding agent. The task message starts with your role and its rules; follow them strictly. Write your explanations and reports in the language the task is written in.'

/** The role header that opens every task message of that role. */
export function roleHeader(role: AgentRole): string {
  return `[ROLE: ${role.toUpperCase()}] ${ROLE_PROMPTS[role].prompt}`
}

/** 'reject' when the session's role may not use this kind of tool (OpenCode offers every role the same tools). */
export function rolePolicyReply(role: AgentRole | undefined, permissionType: string): 'reject' | null {
  if (!role) return null
  const def = ROLE_PROMPTS[role]
  if (def.edit === 'deny' && ['edit', 'write', 'patch', 'multiedit'].includes(permissionType)) return 'reject'
  if (def.bash === 'deny' && permissionType === 'bash') return 'reject'
  return null
}

/** Model key inside the generated config; llama-server serves exactly one model, so the name is an alias. */
export const AGENT_MODEL_KEY = 'netrunner-agent'

/**
 * OpenCode configuration generated by NETRUNNER. The only provider is the local llama-server (loopback,
 * per-launch API key); every edit and shell command needs approval; leaving the workspace is denied;
 * web fetch only in ONLINE TOOLS.
 */
export function buildOpencodeConfig(
  backend: { baseURL: string; apiKey: string; label: string; contextLength: number },
  mode: NetworkMode,
  webTools: { url: string; key: string } | null = null,
): Record<string, unknown> {
  const base = assertInferenceEndpoint(backend.baseURL, mode)
  if (!isLoopback(base.hostname.replace(/^\[|\]$/g, ''))) throw new Error('Agent backend must be on loopback')
  const model = AGENT_MODEL_KEY
  const web = mode === 'online-tools' ? 'ask' : 'deny'
  // OpenCode's own websearch is a cloud service; search comes from NETRUNNER's web tools (MCP) instead.
  const websearch = 'deny'
  const agent: Record<string, unknown> = {}
  for (const [role, def] of Object.entries(ROLE_PROMPTS)) {
    agent[role] = {
      mode: 'primary',
      description: def.description,
      prompt: AGENT_PROMPT,
      model: `${PROVIDER_ID}/${model}`,
      // Same permissions (so the same tools) for every role; a role's own limits are applied in rolePolicyReply.
      permission: { edit: 'ask', bash: 'ask', webfetch: web, websearch, external_directory: 'deny' },
    }
  }
  return {
    $schema: 'https://opencode.ai/config.json',
    autoupdate: false,
    share: 'disabled',
    enabled_providers: [PROVIDER_ID],
    provider: {
      [PROVIDER_ID]: {
        npm: '@ai-sdk/openai-compatible',
        name: 'llama.cpp (local, NETRUNNER)',
        options: { baseURL: new URL('/v1', base).toString(), apiKey: backend.apiKey },
        models: { [model]: { name: backend.label, tools: true, limit: { context: backend.contextLength, output: 16384 } } },
      },
    },
    model: `${PROVIDER_ID}/${model}`,
    small_model: `${PROVIDER_ID}/${model}`,
    permission: {
      edit: 'ask',
      bash: 'ask',
      webfetch: web,
      websearch,
      external_directory: 'deny',
      doom_loop: 'ask',
    },
    agent,
    // NETRUNNER's web tools (search, pages, repositories) on loopback; NETRUNNER asks the operator as WEB TOOLS says.
    ...(webTools ? { mcp: { netrunner: { type: 'remote', url: webTools.url, enabled: true, headers: { Authorization: `Bearer ${webTools.key}` } } } } : {}),
  }
}

/** Environment for the OpenCode process: isolated state dirs, no cloud keys, network-reducing flags. */
export function buildOpencodeEnv(base: Record<string, string | undefined>, dataDir: string, extra: Record<string, string>): Record<string, string> {
  const env: Record<string, string> = {}
  for (const [k, v] of Object.entries(base)) {
    if (v === undefined) continue
    // Never hand cloud credentials to the agent: OpenCode auto-enables providers it finds keys for.
    if (/(_API_KEY|_ACCESS_TOKEN|_AUTH_TOKEN|^AWS_|^AZURE_|^GOOGLE_APPLICATION|^ANTHROPIC|^OPENAI|^OPENROUTER|^GITHUB_TOKEN|^OPENCODE_)/i.test(k)) continue
    env[k] = v
  }
  Object.assign(env, {
    XDG_CONFIG_HOME: path.join(dataDir, 'config'),
    XDG_DATA_HOME: path.join(dataDir, 'data'),
    XDG_CACHE_HOME: path.join(dataDir, 'cache'),
    XDG_STATE_HOME: path.join(dataDir, 'state'),
    OPENCODE_DISABLE_AUTOUPDATE: '1',
    OPENCODE_DISABLE_MODELS_FETCH: '1',
    OPENCODE_DISABLE_LSP_DOWNLOAD: '1',
    OPENCODE_DISABLE_DEFAULT_PLUGINS: '1',
    OPENCODE_DISABLE_EXTERNAL_SKILLS: '1',
    OPENCODE_DISABLE_CLAUDE_CODE: '1',
    OPENCODE_DISABLE_EMBEDDED_WEB_UI: '1',
    // A repository must not be able to loosen NETRUNNER's permission policy with its own opencode.json.
    OPENCODE_DISABLE_PROJECT_CONFIG: '1',
    OPENCODE_PURE: '1',
  })
  Object.assign(env, extra)
  return env
}

/** Ask the OS for an unused loopback port. */
export function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const srv = net.createServer()
    srv.unref()
    srv.once('error', reject)
    srv.listen(0, '127.0.0.1', () => {
      const { port } = srv.address() as net.AddressInfo
      srv.close(() => resolve(port))
    })
  })
}

function gitBashPath(): string | null {
  const candidates = [
    path.join(process.env.ProgramFiles ?? 'C:\\Program Files', 'Git', 'bin', 'bash.exe'),
    path.join(process.env['ProgramFiles(x86)'] ?? 'C:\\Program Files (x86)', 'Git', 'bin', 'bash.exe'),
  ]
  return candidates.find(p => fs.existsSync(p)) ?? null
}

function textOf(e: unknown): string {
  if (!e) return 'unknown error'
  if (typeof e === 'string') return e
  const o = e as { data?: { message?: string }; message?: string; name?: string }
  return o.data?.message ?? o.message ?? o.name ?? JSON.stringify(e)
}

/** Map an OpenCode message part to the NETRUNNER UI model; unknown part types are skipped. */
export function mapPart(part: Record<string, unknown>, role: 'user' | 'assistant'): AgentPart | null {
  const id = String(part.id)
  const messageId = String(part.messageID)
  if (part.type === 'text') {
    if (part.synthetic || part.ignored) return null
    // The role header NETRUNNER puts in front of a task (roleHeader) is for the model, not for the feed.
    const text = String(part.text ?? '')
    return { kind: 'text', id, messageId, role, text: role === 'user' ? text.replace(/^\[ROLE: [A-Z]+\][^\n]*\n\n/, '') : text }
  }
  if (part.type === 'reasoning') return { kind: 'reasoning', id, messageId, text: String(part.text ?? '') }
  if (part.type === 'tool') {
    const state = (part.state ?? {}) as Record<string, unknown>
    const status = String(state.status ?? 'pending') as 'pending' | 'running' | 'completed' | 'error'
    return {
      kind: 'tool',
      id,
      messageId,
      tool: String(part.tool),
      status,
      title: String(state.title ?? part.tool ?? ''),
      input: (state.input as Record<string, unknown>) ?? {},
      output: typeof state.output === 'string' ? state.output.slice(0, 20000) : '',
      error: typeof state.error === 'string' ? state.error : null,
    }
  }
  return null
}

interface Deps {
  binary: string
  dataDir: string
  /** Load the model in the local runtime, pin it for the agent, and return how to reach it. */
  acquireModel: (model: string, lanes: number) => Promise<{ baseURL: string; apiKey: string; label: string; contextLength: number }>
  releaseModel: () => void
  getMode: () => NetworkMode
  proxyEnv: () => Promise<Record<string, string>>
  /** Folder holding rg.exe for OpenCode's grep/glob tools (put first on its PATH), or null. */
  ripgrepDir?: () => string | null
  /** NETRUNNER's web tools as an MCP server (started on demand), or null. */
  webTools?: () => Promise<{ url: string; key: string } | null>
  emit: (e: AgentEvent) => void
}

/** Supervises one OpenCode server bound to the open workspace and relays its events. */
/**
 * What an ALWAYS approval covers: exactly this command, exactly this file, exactly these patterns — never OpenCode's
 * own wildcard ("npm *" would let any npm command through). null: nothing exact to remember, so it counts as once.
 */
export function grantKey(p: AgentPermission): string | null {
  const meta = p.metadata ?? {}
  if (p.type === 'bash') {
    const cmd = typeof meta.command === 'string' ? meta.command : p.pattern.join(' ')
    return cmd.trim() ? `bash:${cmd.trim()}` : null
  }
  if (p.type === 'edit') {
    const file = [meta.filepath, meta.filePath, meta.path, p.pattern[0]].find((v): v is string => typeof v === 'string' && !!v)
    return file ? `edit:${file}` : null
  }
  return p.pattern.length ? `${p.type}:${p.pattern.join('|')}` : null
}

export class OpenCodeService {
  /** ALWAYS approvals of this engine run, by exact key (see grantKey); cleared when the engine stops. */
  private readonly grants = new Map<string, AgentGrant>()
  /** Requests waiting for the operator, so an ALWAYS reply knows what it covers. */
  private readonly pendingPermissions = new Map<string, AgentPermission>()
  private proc: ChildProcess | null = null
  private client: OpencodeClient | null = null
  private auth = ''
  private events: AbortController | null = null
  private readonly roles = new Map<string, 'user' | 'assistant'>()
  /** Sessions created in a worktree: every request about them must name that directory. */
  private readonly dirs = new Map<string, string>()
  /** The role each session works in (sub-agent sessions inherit their parent's), for rolePolicyReply. */
  private readonly sessionRoles = new Map<string, AgentRole>()
  private st: AgentEngineState = { status: 'stopped', url: null, workspace: null, model: null, version: null, error: null, lanes: 1 }

  constructor(private readonly deps: Deps) {}

  get binaryPath(): string {
    return this.deps.binary
  }

  get state(): AgentEngineState {
    return { ...this.st }
  }

  private set(partial: Partial<AgentEngineState>): void {
    this.st = { ...this.st, ...partial }
    this.deps.emit({ type: 'engine', state: this.state })
  }

  private requireClient(): OpencodeClient {
    if (!this.client || this.st.status !== 'running') throw new Error('Agent engine is not running')
    return this.client
  }

  /** `lanes`: jobs that may run at once; the model server gets one sequence slot per lane. */
  async start(workspace: string, model: string, lanes = 1): Promise<AgentEngineState> {
    await this.stop()
    if (!fs.existsSync(this.deps.binary)) throw new Error(`OpenCode binary not found: ${this.deps.binary}`)
    this.set({ status: 'starting', workspace, model, error: null, url: null, lanes })

    try {
      const version = await new Promise<string>((resolve, reject) =>
        execFile(this.deps.binary, ['--version'], { timeout: 15000, windowsHide: true }, (err, out) => (err ? reject(err) : resolve(out.trim()))),
      )
      // Loading a large model can take minutes; the UI shows STARTING meanwhile.
      const backend = await this.deps.acquireModel(model, lanes)
      const config = buildOpencodeConfig(backend, this.deps.getMode(), (await this.deps.webTools?.()) ?? null)
      const password = crypto.randomBytes(24).toString('hex')
      this.auth = `Basic ${Buffer.from(`netrunner:${password}`).toString('base64')}`
      const bash = gitBashPath()
      const rgDir = this.deps.ripgrepDir?.() ?? null
      const baseEnv = buildOpencodeEnv(process.env, this.deps.dataDir, {
        ...(await this.deps.proxyEnv()),
        OPENCODE_CONFIG_CONTENT: JSON.stringify(config),
        OPENCODE_SERVER_USERNAME: 'netrunner',
        OPENCODE_SERVER_PASSWORD: password,
        ...(bash ? { OPENCODE_GIT_BASH_PATH: bash } : {}),
      })
      const env = rgDir ? withPathFirst(baseEnv, rgDir) : baseEnv

      // OpenCode treats --port=0 as its default 4096, which collides with a user's own OpenCode instance.
      const port = await freePort()
      const proc = spawn(this.deps.binary, ['serve', '--hostname=127.0.0.1', `--port=${port}`], {
        cwd: workspace,
        env: env as NodeJS.ProcessEnv,
        windowsHide: true,
        stdio: ['ignore', 'pipe', 'pipe'],
      })
      this.proc = proc
      const url = await new Promise<string>((resolve, reject) => {
        let out = ''
        const timer = setTimeout(() => reject(new Error(`OpenCode did not start within 60 s\n${out.slice(-2000)}`)), 60000)
        const onData = (chunk: Buffer) => {
          out += chunk.toString()
          const m = out.match(/opencode server listening on (http:\/\/127\.0\.0\.1:\d+)/)
          if (m) {
            clearTimeout(timer)
            resolve(m[1])
          }
        }
        proc.stdout?.on('data', onData)
        proc.stderr?.on('data', onData)
        proc.once('exit', code => {
          clearTimeout(timer)
          reject(new Error(`OpenCode exited with code ${code}\n${out.slice(-2000)}`))
        })
      })
      proc.once('exit', code => {
        if (this.proc === proc) {
          this.proc = null
          this.client = null
          this.set({ status: 'error', error: `OpenCode exited (code ${code})`, url: null })
        }
      })

      this.client = createOpencodeClient({ baseUrl: url, headers: { Authorization: this.auth } })
      this.set({ status: 'running', url, version })
      void this.pumpEvents(url)
      return this.state
    } catch (err) {
      await this.stop()
      this.set({ status: 'error', error: err instanceof Error ? err.message : String(err) })
      throw err
    }
  }

  async stop(): Promise<AgentEngineState> {
    this.events?.abort()
    this.events = null
    const proc = this.proc
    this.proc = null
    this.client = null
    this.dirs.clear()
    this.grants.clear()
    this.pendingPermissions.clear()
    this.deps.releaseModel()
    if (proc && proc.exitCode === null) {
      if (process.platform === 'win32' && proc.pid) {
        // Kill the whole tree: the agent may have spawned shells and test runners.
        await new Promise<void>(r => execFile('taskkill', ['/pid', String(proc.pid), '/T', '/F'], { windowsHide: true }, () => r()))
      } else proc.kill()
    }
    if (this.st.status !== 'stopped') this.set({ status: 'stopped', url: null })
    return this.state
  }

  /**
   * Server-sent events → AgentEvent. `/global/event` carries the events of every directory the server works in
   * (the workspace and the worktrees of parallel jobs), each as `{ directory, payload }`. Reconnects while running.
   */
  private async pumpEvents(url: string): Promise<void> {
    while (this.st.status === 'running' && this.st.url === url) {
      const controller = new AbortController()
      this.events = controller
      try {
        const res = await fetch(`${url}/global/event`, { headers: { Authorization: this.auth, Accept: 'text/event-stream' }, signal: controller.signal })
        if (!res.ok || !res.body) throw new Error(`event stream ${res.status}`)
        const reader = res.body.getReader()
        const decoder = new TextDecoder()
        let buf = ''
        while (true) {
          const { value, done } = await reader.read()
          if (done) break
          buf += decoder.decode(value, { stream: true })
          let idx: number
          while ((idx = buf.indexOf('\n\n')) >= 0) {
            const block = buf.slice(0, idx)
            buf = buf.slice(idx + 2)
            const data = block
              .split('\n')
              .filter(l => l.startsWith('data:'))
              .map(l => l.slice(5).trimStart())
              .join('\n')
            if (!data) continue
            const ev = JSON.parse(data) as { payload?: { type: string; properties: Record<string, unknown> } }
            if (ev.payload?.type) this.handle(ev.payload)
          }
        }
      } catch (err) {
        if (controller.signal.aborted) return
        this.deps.emit({ type: 'error', sessionId: null, message: `event stream: ${textOf(err)}` })
      }
      await new Promise(r => setTimeout(r, 1000))
    }
  }

  private handle(ev: { type: string; properties: Record<string, unknown> }): void {
    const p = ev.properties ?? {}
    switch (ev.type) {
      case 'message.updated': {
        const info = p.info as { id: string; sessionID: string; role: 'user' | 'assistant'; tokens?: { input: number; output: number }; error?: unknown }
        this.roles.set(info.id, info.role)
        if (info.role === 'assistant' && info.tokens) {
          this.deps.emit({ type: 'tokens', sessionId: info.sessionID, input: info.tokens.input, output: info.tokens.output })
        }
        if (info.error) this.deps.emit({ type: 'error', sessionId: info.sessionID, message: textOf(info.error) })
        break
      }
      case 'message.part.updated': {
        const part = p.part as Record<string, unknown>
        const mapped = mapPart(part, this.roles.get(String(part.messageID)) ?? 'assistant')
        if (mapped) this.deps.emit({ type: 'part', sessionId: String(part.sessionID), part: mapped })
        break
      }
      case 'session.status': {
        const status = p.status as { type: string; message?: string; attempt?: number }
        this.deps.emit({
          type: 'status',
          sessionId: String(p.sessionID),
          busy: status.type !== 'idle',
          detail: status.type === 'retry' ? `retry ${status.attempt}: ${status.message}` : null,
        })
        break
      }
      case 'session.idle':
        this.deps.emit({ type: 'status', sessionId: String(p.sessionID), busy: false, detail: null })
        break
      // A sub-agent (task tool) works under the role of the session that started it.
      case 'session.created':
      case 'session.updated': {
        const info = p.info as { id?: string; parentID?: string } | undefined
        const parentRole = info?.parentID ? this.sessionRoles.get(info.parentID) : undefined
        if (info?.id && parentRole && !this.sessionRoles.has(info.id)) this.sessionRoles.set(info.id, parentRole)
        break
      }
      case 'session.error':
        this.deps.emit({ type: 'error', sessionId: (p.sessionID as string) ?? null, message: textOf(p.error) })
        break
      // OpenCode ≥1.x emits `permission.asked` (v2 shape); `permission.updated` is the legacy v1 event.
      case 'permission.asked':
      case 'permission.updated': {
        const perm = p as {
          id: string
          sessionID: string
          permission?: string
          type?: string
          title?: string
          patterns?: string[]
          pattern?: string | string[]
          metadata?: Record<string, unknown>
        }
        const pattern = perm.patterns ?? (perm.pattern === undefined ? [] : Array.isArray(perm.pattern) ? perm.pattern : [perm.pattern])
        const type = perm.permission ?? perm.type ?? 'unknown'
        const permission: AgentPermission = {
          id: perm.id,
          sessionId: perm.sessionID,
          type,
          title: perm.title ?? (pattern.length ? pattern.join(' ') : type),
          pattern,
          metadata: perm.metadata ?? {},
        }
        // What the role may not do is refused here, before the operator is asked (and before any ALWAYS grant).
        if (rolePolicyReply(this.sessionRoles.get(permission.sessionId), permission.type) === 'reject') {
          void this.reply(permission.sessionId, permission.id, 'reject').catch(() => undefined)
          break
        }
        // An exact match of a standing ALWAYS approval is answered here, once, and shown in the feed.
        const key = grantKey(permission)
        const grant = key ? this.grants.get(key) : undefined
        if (grant) {
          grant.uses++
          void this.reply(permission.sessionId, permission.id, 'once').catch(() => undefined)
          this.deps.emit({ type: 'permission-auto', sessionId: permission.sessionId, permission, grant: { ...grant } })
          break
        }
        this.pendingPermissions.set(permission.id, permission)
        this.deps.emit({ type: 'permission', permission })
        break
      }
      case 'permission.replied':
        this.deps.emit({
          type: 'permission-replied',
          sessionId: String(p.sessionID),
          permissionId: String(p.requestID ?? p.permissionID),
          response: String(p.reply ?? p.response),
        })
        break
    }
  }

  private unwrap<T>(res: { data?: T; error?: unknown }): T {
    if (res.error !== undefined && res.error !== null) throw new Error(textOf(res.error))
    return res.data as T
  }

  async sessions(): Promise<AgentSessionInfo[]> {
    const list = this.unwrap(await this.requireClient().session.list())
    return list
      .filter(s => !s.parentID)
      .map(s => ({ id: s.id, title: s.title, created: s.time.created, updated: s.time.updated }))
      .sort((a, b) => b.updated - a.updated)
  }

  /** The `directory` query that scopes a request to the session's worktree (none for workspace sessions). */
  private scope(sessionId: string): { directory: string } | undefined {
    const d = this.dirs.get(sessionId)
    return d ? { directory: d } : undefined
  }

  /** `directory`: a worktree of a parallel job; OpenCode then works (and confines the agent) there. */
  async createSession(title: string, directory?: string): Promise<AgentSessionInfo> {
    const s = this.unwrap(
      await this.requireClient().session.create({ body: { title: title.slice(0, 120) || 'NETRUNNER task' }, ...(directory ? { query: { directory } } : {}) }),
    )
    if (directory) this.dirs.set(s.id, directory)
    return { id: s.id, title: s.title, created: s.time.created, updated: s.time.updated }
  }

  async history(sessionId: string): Promise<AgentPart[]> {
    const msgs = this.unwrap(await this.requireClient().session.messages({ path: { id: sessionId }, query: this.scope(sessionId) }))
    const parts: AgentPart[] = []
    for (const m of msgs) {
      this.roles.set(m.info.id, m.info.role)
      for (const part of m.parts) {
        const mapped = mapPart(part as unknown as Record<string, unknown>, m.info.role)
        if (mapped) parts.push(mapped)
      }
    }
    return parts
  }

  async prompt(req: AgentPromptRequest): Promise<void> {
    if (!(req.role in ROLE_PROMPTS)) throw new Error(`Unknown role ${req.role}`)
    this.sessionRoles.set(req.sessionId, req.role)
    this.unwrap(
      await this.requireClient().session.promptAsync({
        path: { id: req.sessionId },
        query: this.scope(req.sessionId),
        body: { agent: req.role, model: { providerID: PROVIDER_ID, modelID: AGENT_MODEL_KEY }, parts: [{ type: 'text', text: `${roleHeader(req.role)}

${req.text}` }] },
      }),
    )
  }

  async abort(sessionId: string): Promise<void> {
    this.unwrap(await this.requireClient().session.abort({ path: { id: sessionId }, query: this.scope(sessionId) }))
  }

  /**
   * The operator's answer. ALWAYS is kept by NETRUNNER as an exact grant (this command / this file) and passed to
   * OpenCode as "once", so OpenCode's wildcard patterns never widen it.
   */
  async respond(sessionId: string, permissionId: string, response: 'once' | 'always' | 'reject'): Promise<void> {
    if (!['once', 'always', 'reject'].includes(response)) throw new Error('Invalid response')
    const asked = this.pendingPermissions.get(permissionId)
    this.pendingPermissions.delete(permissionId)
    if (response === 'always' && asked) {
      const key = grantKey(asked)
      if (key && !this.grants.has(key)) this.grants.set(key, { key, type: asked.type, what: key.slice(key.indexOf(':') + 1), uses: 0, since: new Date().toISOString() })
    }
    await this.reply(sessionId, permissionId, response === 'always' ? 'once' : response)
  }

  /** Standing ALWAYS approvals of this engine run. */
  listGrants(): AgentGrant[] {
    return [...this.grants.values()].map(g => ({ ...g }))
  }

  revokeGrant(key: string): AgentGrant[] {
    this.grants.delete(key)
    return this.listGrants()
  }

  /** Reply through the current endpoint (POST /permission/{id}/reply); the v1 SDK only knows the legacy route. */
  private async reply(sessionId: string, permissionId: string, response: 'once' | 'reject'): Promise<void> {
    this.requireClient()
    if (!/^[\w-]+$/.test(permissionId) || !/^[\w-]+$/.test(sessionId)) throw new Error('Invalid id')
    const dir = this.dirs.get(sessionId)
    const res = await fetch(`${this.st.url}/permission/${permissionId}/reply${dir ? `?directory=${encodeURIComponent(dir)}` : ''}`, {
      method: 'POST',
      headers: { Authorization: this.auth, 'content-type': 'application/json' },
      body: JSON.stringify({ reply: response }),
    })
    if (!res.ok) throw new Error(`permission reply failed: ${res.status} ${await res.text()}`)
  }
}
